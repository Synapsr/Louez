import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { before, describe, mock, test } from "node:test";

// tsx loads these packages as CommonJS, whose `export *` names ESM cannot see.
// The app's router reaches @louez/validations too.
const require = createRequire(import.meta.url);
for (const name of ["@louez/types", "@louez/utils", "@louez/validations"]) {
  const namedExports: Record<string, unknown> = require(name);
  mock.module(name, { namedExports });
}
// The app's router loads @louez/auth, which reads the database URL. Nothing connects.
process.env.DATABASE_URL ??= "mysql://unused:unused@127.0.0.1:1/unused";

// The document /api/v1/openapi.json serves, generated by oRPC from the
// exposed router: valid OpenAPI 3.1, with the API key scheme and the
// idempotency, confirmation and receipt headers.

type Document = {
  openapi: string;
  security?: unknown;
  components: {
    securitySchemes: Record<string, { type: string; scheme: string }>;
    parameters: Record<string, { name: string; in: string }>;
  };
  paths: Record<
    string,
    Record<
      string,
      {
        operationId: string;
        parameters?: Array<{ $ref?: string; name?: string; in?: string }>;
        responses: Record<string, { headers?: Record<string, unknown> }>;
      }
    >
  >;
};

describe("OpenAPI document", () => {
  let document: Document;

  before(async () => {
    const { createExposure } = await import("./exposure");
    const { generateOpenApiDocument } = await import("./openapi");
    const { createFixtureRouter, FIXTURE_EXPOSED } = await import("./testing");
    const exposure = createExposure(createFixtureRouter(), FIXTURE_EXPOSED);
    document = (await generateOpenApiDocument(
      exposure.router,
      "https://app.louez.test/api/v1",
    )) as unknown as Document;
  });

  test("is an OpenAPI 3.1 document whose every operation is named and answers", () => {
    assert.match(document.openapi, /^3\.1\./);
    const operations = Object.values(document.paths).flatMap((methods) => Object.values(methods));
    assert.ok(operations.length > 0);
    for (const operation of operations) {
      assert.ok(operation.operationId, "every operation has an id");
      assert.ok(Object.keys(operation.responses).length > 0, `${operation.operationId} answers`);
    }
    // Every reference points at something the document defines.
    const text = JSON.stringify(document);
    for (const [, kind, name] of text.matchAll(/"#\/components\/(\w+)\/([\w.-]+)"/g)) {
      const defined = (document.components as Record<string, Record<string, unknown> | undefined>)[
        kind
      ];
      assert.ok(defined?.[name], `#/components/${kind}/${name} is defined`);
    }
  });

  test("asks for a bearer API key", () => {
    assert.deepEqual(document.security, [{ apiKey: [] }]);
    assert.equal(document.components.securitySchemes.apiKey.type, "http");
    assert.equal(document.components.securitySchemes.apiKey.scheme, "bearer");
  });

  test("documents the idempotency and confirmation headers where they apply", () => {
    const { parameters } = document.components;
    assert.deepEqual(
      [parameters.IdempotencyKey.name, parameters.IdempotencyKey.in],
      ["Idempotency-Key", "header"],
    );
    assert.deepEqual(
      [parameters.LouezConfirmation.name, parameters.LouezConfirmation.in],
      ["Louez-Confirmation", "header"],
    );

    const read = document.paths["/fixture/notes/list"].post;
    const write = document.paths["/fixture/notes/remove"].post;
    assert.equal(read.operationId, "fixture_notes_list");
    assert.equal(write.operationId, "fixture_notes_remove");

    const refs = (operation: typeof read) => (operation.parameters ?? []).map((p) => p.$ref);
    assert.deepEqual(refs(read), []);
    assert.deepEqual(refs(write), [
      "#/components/parameters/IdempotencyKey",
      "#/components/parameters/LouezConfirmation",
    ]);
    assert.deepEqual(Object.keys(write.responses["200"].headers ?? {}), [
      "Louez-Operation-Id",
      "Louez-Replayed",
    ]);
  });

  test("serves the categories at short REST paths named after their tools", async () => {
    const { createExposure } = await import("./exposure");
    const { generateOpenApiDocument } = await import("./openapi");
    const { appRouter } = await import("../router");
    const app = (await generateOpenApiDocument(
      createExposure(appRouter).router,
    )) as unknown as Document;

    const operations = Object.fromEntries(
      Object.entries(app.paths).flatMap(([path, methods]) =>
        Object.entries(methods).map(([method, operation]) => [
          `${method.toUpperCase()} ${path}`,
          operation,
        ]),
      ),
    );
    assert.deepEqual(
      Object.fromEntries(
        Object.entries(operations).map(([route, operation]) => [route, operation.operationId]),
      ),
      {
        "GET /categories": "categories_list",
        "POST /categories": "categories_create",
        "GET /categories/{id}": "categories_get",
        "PATCH /categories/{id}": "categories_update",
        "DELETE /categories/{id}": "categories_delete",
        "POST /categories/reorder": "categories_reorder",
        "POST /categories/image-uploads": "categories_create_image_upload",
        "POST /categories/image-uploads/complete": "categories_complete_image_upload",
      },
    );

    const refs = (route: string) =>
      (operations[route].parameters ?? []).flatMap((parameter) =>
        parameter.$ref ? [parameter.$ref] : [],
      );
    assert.deepEqual(refs("DELETE /categories/{id}"), [
      "#/components/parameters/IdempotencyKey",
      "#/components/parameters/LouezConfirmation",
    ]);
    assert.deepEqual(refs("POST /categories"), ["#/components/parameters/IdempotencyKey"]);
    // Its output is an upload URL: never stored, so no idempotency key.
    assert.deepEqual(refs("POST /categories/image-uploads"), []);
    assert.deepEqual(
      (operations["GET /categories"].parameters ?? []).map((p) => `${p.in}:${p.name}`).sort(),
      ["query:cursor", "query:limit"],
    );
    assert.deepEqual(
      (operations["PATCH /categories/{id}"].parameters ?? [])
        .filter((p) => p.in === "path")
        .map((p) => p.name),
      ["id"],
    );
  });
});
