// The document /api/v1/openapi.json serves, generated by oRPC from the
// exposed router: valid OpenAPI 3.1, with the API key scheme and the
// idempotency, confirmation and receipt headers.

type Document = {
  openapi: string;
  security?: unknown;
  components: {
    securitySchemes: Record<string, { type: string; scheme: string }>;
    parameters: Record<string, { name: string; in: string }>;
  };
  paths: Record<
    string,
    Record<
      string,
      {
        operationId: string;
        parameters?: Array<{ $ref?: string; name?: string; in?: string }>;
        responses: Record<string, { headers?: Record<string, unknown> }>;
      }
    >
  >;
};

