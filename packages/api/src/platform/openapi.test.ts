        "GET /products/{id}/activity": "products_get_activity",
        "GET /products/{id}/reservation-timeline": "products_get_reservation_timeline",
        "GET /products/{productId}/seasonal-pricings": "products_list_seasonal_pricings",
        "POST /products/{productId}/seasonal-pricings": "products_create_seasonal_pricing",
        "PATCH /products/seasonal-pricings/{id}": "products_update_seasonal_pricing",
        "POST /products/seasonal-pricings/{id}/duplicate": "products_duplicate_seasonal_pricing",
        "DELETE /products/seasonal-pricings/{id}": "products_delete_seasonal_pricing",
        "GET /products/units/{unitId}/history": "products_get_unit_history",
        "POST /products/units/{unitId}/downtimes": "products_declare_downtime",
        "PATCH /products/downtimes/{downtimeId}": "products_update_downtime",
        "POST /products/downtimes/{downtimeId}/close": "products_close_downtime",
        "DELETE /products/downtimes/{downtimeId}": "products_delete_downtime",
        "POST /products/units/{unitId}/retire": "products_retire_unit",
        "POST /products/units/{unitId}/reinstate": "products_reinstate_unit",
        "PATCH /products/units/{unitId}": "products_update_unit_details",
        "GET /variants": "products_list_variants",
        "POST /variants": "products_create_variant",
        "PATCH /variants/{id}": "products_update_variant",
