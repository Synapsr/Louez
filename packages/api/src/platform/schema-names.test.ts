import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { describe, mock, test } from "node:test";

// tsx loads @louez/types as CommonJS, whose `export *` names ESM cannot see.
const require = createRequire(import.meta.url);
mock.module("@louez/types", { namedExports: require("@louez/types") });

const schema = await import("@louez/db/schema");
const { getTableConfig, MySqlTable } = await import("drizzle-orm/mysql-core");
const { SCHEMA_NAMES } = await import("./schema-names");

/** The names Louez's Drizzle schema writes, by kind. */
function collect() {
  const names = {
    table: new Set<string>(),
    column: new Set<string>(),
    key: new Set<string>(["PRIMARY"]),
    constraint: new Set<string>(),
  };
  for (const value of Object.values(schema)) {
    if (!(value instanceof MySqlTable)) continue;
    const config = getTableConfig(value);
    names.table.add(config.name);
    for (const column of config.columns) {
      names.column.add(column.name);
      if (column.isUnique && column.uniqueName) names.key.add(column.uniqueName);
    }
    for (const index of config.indexes) names.key.add(index.config.name);
    for (const unique of config.uniqueConstraints) {
      const name = unique.getName();
      if (name) names.key.add(name);
    }
    for (const primary of config.primaryKeys) names.key.add(primary.getName());
    for (const foreign of config.foreignKeys) names.constraint.add(foreign.getName());
    for (const check of config.checks) names.constraint.add(check.name);
  }
  return names;
}

function render(names: ReturnType<typeof collect>) {
  const list = (set: Set<string>) =>
    [...set]
      .sort()
      .map((name) => `    "${name}",`)
      .join("\n");
  return `/**
 * The names Louez's Drizzle schema (\`@louez/db/schema\`) gives its tables,
 * columns, keys and constraints. A report keeps a schema object a database
 * error names only when it is one of these (\`sanitizeError\`).
 * Generated by \`schema-names.test.ts\`, which fails when the schema
 * changes: run it with UPDATE_SCHEMA_NAMES=1 to write this file again.
 */
export const SCHEMA_NAMES = {
  table: new Set([
${list(names.table)}
  ]),
  column: new Set([
${list(names.column)}
  ]),
  key: new Set([
${list(names.key)}
  ]),
  constraint: new Set([
${list(names.constraint)}
  ]),
} as const satisfies Record<string, ReadonlySet<string>>;
`;
}

describe("the schema's names", () => {
  test("list every table, column, key and constraint the Drizzle schema writes", () => {
    const names = collect();
    if (process.env.UPDATE_SCHEMA_NAMES === "1") {
      writeFileSync(fileURLToPath(new URL("./schema-names.ts", import.meta.url)), render(names));
      return;
    }
    assert.ok(names.table.size > 50, "the schema's tables were not found");
    for (const kind of ["table", "column", "key", "constraint"] as const) {
      assert.deepEqual(
        [...SCHEMA_NAMES[kind]].sort(),
        [...names[kind]].sort(),
        `platform/schema-names.ts is out of step with the schema's ${kind}s: run this test with UPDATE_SCHEMA_NAMES=1`,
      );
    }
  });
});
