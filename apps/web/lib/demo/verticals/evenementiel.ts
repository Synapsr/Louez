/** Event pricing: the weekend (3 days) costs about one and a half days. */
function eventLadder(daily: number): DemoRate[] {
  return [
    { period: 2 * DAY, price: Math.round(daily * 1.3) },
    { period: 3 * DAY, price: Math.round(daily * 1.5) },
    { period: 7 * DAY, price: Math.round(daily * 2.5) },
  ];
}

