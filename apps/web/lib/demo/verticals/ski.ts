/** The usual ski-shop ladder: the longer the stay, the cheaper the day; a week is six days. */
function skiLadder(daily: number): DemoRate[] {
  return [
    { period: 2 * DAY, price: Math.round(daily * 2 * 0.95) },
    { period: 3 * DAY, price: Math.round(daily * 3 * 0.9) },
    { period: 4 * DAY, price: Math.round(daily * 4 * 0.85) },
    { period: 5 * DAY, price: Math.round(daily * 5 * 0.8) },
    { period: 6 * DAY, price: Math.round(daily * 6 * 0.75) },
    { period: 7 * DAY, price: Math.round(daily * 7 * 0.72) },
  ];
}

